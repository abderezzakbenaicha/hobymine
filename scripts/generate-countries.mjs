import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const source = readFileSync(resolve('node_modules/world-countries/countries.json'), 'utf8');
const raw = JSON.parse(source);

const countries = raw
  .filter((country) => country.cca2 && country.name?.common && country.latlng?.length === 2)
  .map((country) => ({
    code: country.cca2,
    name: country.name.common,
    flag: country.flag,
    lat: Number(country.latlng[0].toFixed(5)),
    lng: Number(country.latlng[1].toFixed(5)),
    region: country.region || 'Other',
  }))
  .sort((a, b) => a.name.localeCompare(b.name, 'en'));

const header = `// Generated by scripts/generate-countries.mjs from world-countries (ISO 3166-1).
// Do not edit by hand. Run \`npm run countries\` to refresh.

export interface Country {
  code: string;
  name: string;
  flag: string;
  lat: number;
  lng: number;
  region: string;
}
`;

const web = `${header}
export const COUNTRIES: Country[] = ${JSON.stringify(countries, null, 2)};

export function countryByCode(code: string | null | undefined): Country | undefined {
  if (!code) return undefined;
  const normalized = code.trim().toUpperCase();
  return COUNTRIES.find((country) => country.code === normalized);
}
`;

const api = `${header}
export const COUNTRIES: Country[] = ${JSON.stringify(countries, null, 2)};

const BY_CODE = new Map(COUNTRIES.map((country) => [country.code, country]));

export function countryByCode(code: string | null | undefined): Country | undefined {
  if (!code) return undefined;
  return BY_CODE.get(code.trim().toUpperCase());
}

export function isCountryCode(value: string): boolean {
  return BY_CODE.has(value.trim().toUpperCase());
}
`;

writeFileSync(resolve('apps/web/src/lib/countries.ts'), web);
writeFileSync(resolve('apps/api/src/lib/countries.ts'), api);
console.log(`Generated ${countries.length} countries for web and api.`);
